import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parsePost,buildBlog} from './build-blog.mjs';

const fixture = `---\ntitle: "Test & <example>"\ndate: 2025-06-30\nslug: test-post\n---\n\n# Heading\n\n**Bold** and [safe](https://example.com).\n\n| A | B |\n|---|---|\n| 1 | 2 |\n\n\`\`\`sh\n<script>alert('never executed')</script>\n\`\`\`\n\n<script>alert('unsafe')</script><img src="x" onerror="alert(1)">\n\n[bad](javascript:alert)\n`;
const post = parsePost(fixture,'test.md');
assert.equal(post.title,'Test & <example>');
assert.ok(post.html.includes('<h2 id="post-heading">Heading</h2>'));
assert.ok(post.html.includes('<table>'));
assert.ok(post.html.includes('<strong>Bold</strong>'));
assert.ok(post.html.includes('&lt;script&gt;'));
assert.ok(!post.html.includes('<script>') && !post.html.includes('onerror') && !post.html.includes('javascript:'));
assert.equal(parsePost(fixture.replace('slug: test-post','draft: true'),'test.md'),null);
assert.throws(()=>parsePost(fixture.replace('2025-06-30','2025-02-30'),'test.md'));
assert.throws(()=>parsePost(fixture.replace('slug: test-post','slug: ../escape'),'test.md'));
const posts=buildBlog();
const supplied=posts.find(p=>p.slug==='self-host-nextjs-with-docker-and-nginx');
assert.ok(supplied);
assert.equal(supplied.date,'2025-06-30');
assert.equal(supplied.title,'Self-Host Next.js with Docker and Nginx');
assert.equal((supplied.html.match(/class="blog-missing-image"/g)||[]).length,0);
assert.equal((supplied.html.match(/<img /g)||[]).length,4);
assert.ok(supplied.html.includes('docker build -t my-nextjs-app .'));
assert.ok(supplied.html.includes('https://docs.docker.com/desktop/setup/install/windows-install/'));
assert.ok(supplied.html.includes('https://winscp.net/eng/download.php'));
assert.ok(!supplied.html.includes('![[Screenshot'));
const feed=fs.readFileSync('rss.xml','utf8');
assert.equal((feed.match(/<item>/g)||[]).length,posts.length);
assert.ok(feed.includes('Mon, 30 Jun 2025 12:00:00 GMT'));
assert.ok(feed.includes('https://christopher-scott.net/#blog/self-host-nextjs-with-docker-and-nginx'));
assert.ok(feed.includes('<content:encoded>'));
console.log('PASS: Markdown formatting, code escaping, HTML sanitization, metadata/drafts, article date, repaired source links, and full-content RSS generation.');
